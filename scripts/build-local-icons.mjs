import { readdirSync, writeFileSync } from 'node:fs';
import { ITEMS } from '../src/data/items.js';
const files = readdirSync(new URL('../data/dfhub_collectible_images/', import.meta.url));
const paths = Object.fromEntries(files.filter(f => f.endsWith('.png')).map(f => [f.split('_')[0], './data/dfhub_collectible_images/' + f]));
const mapping = Object.fromEntries(ITEMS.filter(i => paths[i.objectId]).map(i => [i.id, paths[i.objectId]]));
writeFileSync(new URL('../src/data/local-icons.js', import.meta.url), '// Generated by scripts/build-local-icons.mjs; all images are served with the game.\nexport const LOCAL_ICONS = ' + JSON.stringify(mapping, null, 2) + ';\n');
console.log(`${Object.keys(mapping).length} local item images indexed.`);
